struct Package {
    std::map<std::string, std::vector<uint8_t>> files;
};

bool read_package(void* context, std::string_view path, std::vector<uint8_t>& bytes) {
    auto* package = static_cast<Package*>(context);
    const auto found = package->files.find(std::string(path));
    if (found == package->files.end())
        return false;
    bytes = found->second;
    return true;
}

std::optional<host::Sandbox> open_box(Package& package, host::ScriptError& error) {
    host::OpenOptions options;
    options.package_id = "sample";
    options.profile = host::mutator_profile();
    options.sources.context = &package;
    options.sources.read = read_package;
    auto sandbox = host::Sandbox::open(options, error);
    OA_CHECK(sandbox.has_value());
    return sandbox;
}

bool run_source(
    host::Sandbox& sandbox, Package& package, const std::string& source, host::ScriptError& error
) {
    package.files["mutator.lua"] = std::vector<uint8_t>(source.begin(), source.end());
    return sandbox.run_file("mutator.lua", "plan", nullptr, error);
}

std::optional<int64_t> as_count(const char* text) {
    if (text == nullptr || text[0] == '\0' || std::strcmp(text, "error") == 0)
        return std::nullopt;
    int64_t value = 0;
    const char* end = text + std::strlen(text);
    const std::from_chars_result parsed = std::from_chars(text, end, value);
    if (parsed.ec != std::errc{} || parsed.ptr != end)
        return std::nullopt;
    return value;
}

void report_row(const Golden& row, const char* detail) {
    std::fprintf(
        stderr,
        "fixed %s [%s] [%s] [%s] %s\n",
        row.op,
        row.left,
        row.right != nullptr ? row.right : "",
        row.result,
        detail
    );
}

void expect_count(const Golden& row, const std::optional<int64_t>& got) {
    if (std::strcmp(row.result, "error") == 0) {
        if (got.has_value()) {
            report_row(row, "succeeded");
            OA_CHECK(false);
        }
        return;
    }
    const std::optional<int64_t> want = as_count(row.result);
    if (!want.has_value() || got != want) {
        report_row(row, "mismatch");
        OA_CHECK(false);
    }
}

void keep_count(std::set<int64_t>& counts, const char* text) {
    const std::optional<int64_t> count = as_count(text);
    if (count.has_value())
        counts.insert(*count);
}

void check_rows() {
    std::set<int64_t> counts;
    for (const Golden& row : k_rows) {
        const std::string_view op = row.op;
        if (op == "spell") {
            const std::optional<int64_t> count = as_count(row.left);
            OA_CHECK(count.has_value());
            if (!count.has_value())
                continue;
            char text[host::fixed_text_bytes];
            if (!host::fixed_text(*count, text, sizeof text) ||
                std::strcmp(text, row.result) != 0) {
                report_row(row, text);
                OA_CHECK(false);
            }
            counts.insert(*count);
            continue;
        }
        if (op == "parse") {
            expect_count(row, host::fixed_from_text(row.left));
            if (std::strcmp(row.result, "error") != 0)
                keep_count(counts, row.result);
            continue;
        }
        if (op == "number") {
            const double value = std::strtod(row.left, nullptr);
            expect_count(row, host::fixed_from_number(value));
            if (std::strcmp(row.result, "error") != 0)
                keep_count(counts, row.result);
            continue;
        }
        if (op == "floor" || op == "ceil" || op == "round") {
            const std::optional<int64_t> count = as_count(row.left);
            const std::optional<int64_t> want = as_count(row.result);
            OA_CHECK(count.has_value());
            OA_CHECK(want.has_value());
            if (!count.has_value() || !want.has_value())
                continue;
            int64_t got = 0;
            if (op == "floor")
                got = host::fixed_whole_floor(*count);
            else if (op == "ceil")
                got = host::fixed_whole_ceil(*count);
            else
                got = host::fixed_whole_round(*count);
            if (got != *want) {
                report_row(row, "whole");
                OA_CHECK(false);
            }
            counts.insert(*count);
            continue;
        }
        if (op == "neg") {
            const std::optional<int64_t> count = as_count(row.left);
            OA_CHECK(count.has_value());
            if (!count.has_value())
                continue;
            expect_count(row, host::fixed_negate(*count));
            counts.insert(*count);
            if (std::strcmp(row.result, "error") != 0)
                keep_count(counts, row.result);
            continue;
        }
        const std::optional<int64_t> left = as_count(row.left);
        const std::optional<int64_t> right = as_count(row.right);
        OA_CHECK(left.has_value());
        OA_CHECK(right.has_value());
        if (!left.has_value() || !right.has_value())
            continue;
        std::optional<int64_t> got;
        if (op == "mul")
            got = host::fixed_multiply(*left, *right);
        else if (op == "div")
            got = host::fixed_divide(*left, *right);
        else if (op == "add")
            got = host::fixed_add(*left, *right);
        else if (op == "sub")
            got = host::fixed_subtract(*left, *right);
        else {
            report_row(row, "unknown");
            OA_CHECK(false);
            continue;
        }
        expect_count(row, got);
        counts.insert(*left);
        counts.insert(*right);
        if (std::strcmp(row.result, "error") != 0)
            keep_count(counts, row.result);
    }

    OA_CHECK(host::fixed_from_number(1.6) == std::optional<int64_t>{104857});
    OA_CHECK(host::fixed_multiply(104857, 98304) == std::optional<int64_t>{157285});
    OA_CHECK(counts.size() >= 30);

    for (const int64_t count : counts) {
        char text[host::fixed_text_bytes];
        const bool wrote = host::fixed_text(count, text, sizeof text);
        if (!wrote) {
            std::fprintf(stderr, "fixed text failed for %lld\n", static_cast<long long>(count));
            OA_CHECK(false);
            continue;
        }
        const std::optional<std::string> spelled =
            tdf::format_number(static_cast<double>(count) / 65536.0);
        if (!spelled.has_value() || *spelled != text) {
            std::fprintf(
                stderr,
                "spelling %lld got [%s] format [%s]\n",
                static_cast<long long>(count),
                text,
                spelled.has_value() ? spelled->c_str() : "<none>"
            );
            OA_CHECK(false);
        }
        const std::optional<int64_t> again = host::fixed_from_text(text);
        if (again != std::optional<int64_t>{count}) {
            std::fprintf(
                stderr, "round trip %lld text [%s]\n", static_cast<long long>(count), text
            );
            OA_CHECK(false);
        }
    }
}

void pin_loader() {
    for (const Golden& row : k_rows) {
        if (std::strcmp(row.op, "parse") != 0 || std::strcmp(row.result, "error") == 0)
            continue;
        const double parsed = tdf::parse_double(row.left);
        if (!(parsed >= -32768.0 && parsed <= 32768.0))
            continue;
        const std::optional<int64_t> count = host::fixed_from_text(row.left);
        OA_CHECK(count.has_value());
        if (!count.has_value())
            continue;
        const std::string body = std::string("[R]\n{\nk=") + row.left + ";\n}\n";
        tdf::OwnedDocument document;
        if (!document.parse(body) || document.root() == nullptr) {
            report_row(row, "block");
            OA_CHECK(false);
            continue;
        }
        const tdf::Block* section = tdf::find_child(document.root(), "R");
        const auto low = static_cast<int32_t>(static_cast<uint32_t>(static_cast<uint64_t>(*count)));
        const int32_t loaded = tdf::get_fixed(section, "k", 7);
        if (section == nullptr || low != loaded) {
            std::fprintf(
                stderr,
                "loader [%s] low %d loaded %d\n",
                row.left,
                static_cast<int>(low),
                static_cast<int>(loaded)
            );
            OA_CHECK(false);
        }
    }
}

