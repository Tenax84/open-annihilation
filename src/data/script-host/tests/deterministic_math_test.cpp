uint64_t bits_of(double value) {
    return std::bit_cast<uint64_t>(value);
}

double from_bits(uint64_t bits) {
    return std::bit_cast<double>(bits);
}

bool nan_bits(double value) {
    return (bits_of(value) & 0x7fffffffffffffffULL) > 0x7ff0000000000000ULL;
}

double call_maths(const char* name, double left, double right) {
    if (std::strcmp(name, "sine") == 0)
        return host::sine(left);
    if (std::strcmp(name, "cosine") == 0)
        return host::cosine(left);
    if (std::strcmp(name, "tangent") == 0)
        return host::tangent(left);
    if (std::strcmp(name, "arcsine") == 0)
        return host::arcsine(left);
    if (std::strcmp(name, "arccosine") == 0)
        return host::arccosine(left);
    if (std::strcmp(name, "arctangent") == 0)
        return host::arctangent(left, right);
    if (std::strcmp(name, "exponential") == 0)
        return host::exponential(left);
    if (std::strcmp(name, "natural_log") == 0)
        return host::natural_log(left);
    if (std::strcmp(name, "log2") == 0)
        return host::log2(left);
    if (std::strcmp(name, "log10") == 0)
        return host::log10(left);
    return host::power(left, right);
}

void golden_rows_match() {
    const char* names[] = {
        "sine",
        "cosine",
        "tangent",
        "arcsine",
        "arccosine",
        "arctangent",
        "exponential",
        "natural_log",
        "log2",
        "log10",
        "power"
    };
    int counts[11] = {};
    for (const MathsRow& row : maths_rows) {
        const double got = call_maths(row.name, from_bits(row.left), from_bits(row.right));
        if (bits_of(got) != row.expected) {
            std::fprintf(
                stderr,
                "golden %s left 0x%016llx got 0x%016llx expected 0x%016llx\n",
                row.name,
                static_cast<unsigned long long>(row.left),
                static_cast<unsigned long long>(bits_of(got)),
                static_cast<unsigned long long>(row.expected)
            );
        }
        OA_CHECK(bits_of(got) == row.expected);
        for (int index = 0; index < 11; ++index) {
            if (std::strcmp(row.name, names[index]) == 0)
                ++counts[index];
        }
    }
    for (int count : counts)
        OA_CHECK(count >= 40);
}

void powers_of_two_are_exact() {
    for (int power = -1074; power <= 1023; ++power) {
        const double value = std::ldexp(1.0, power);
        const double logged = host::log2(value);
        const double raised = host::power(2.0, static_cast<double>(power));
        if (logged != static_cast<double>(power) || bits_of(raised) != bits_of(value)) {
            std::fprintf(stderr, "power of two %d\n", power);
        }
        OA_CHECK(logged == static_cast<double>(power));
        OA_CHECK(bits_of(raised) == bits_of(value));
    }
    double ten = 1.0;
    for (int power = 0; power <= 22; ++power) {
        OA_CHECK(host::log10(ten) == static_cast<double>(power));
        ten *= 10.0;
    }
}

void repeated_squaring_stops_at_the_limit() {
    // 256 is the magnitude in deterministic_math.hpp. Exponents past it go
    // through exp(y · log x). The golden power rows above 256 are values
    // repeated squaring gets wrong, so raising the limit fails those rows.
    OA_CHECK(host::repeated_squaring_limit == 256);
    const double edge = static_cast<double>(host::repeated_squaring_limit);
    const double at_limit = std::ldexp(1.0, host::repeated_squaring_limit);
    const double past_limit = std::ldexp(1.0, host::repeated_squaring_limit + 1);
    OA_CHECK(bits_of(host::power(2.0, edge)) == bits_of(at_limit));
    OA_CHECK(bits_of(host::power(2.0, edge + 1.0)) == bits_of(past_limit));
    OA_CHECK(bits_of(host::power(-2.0, edge)) == bits_of(at_limit));
    OA_CHECK(bits_of(host::power(-2.0, edge + 1.0)) == bits_of(-past_limit));
    OA_CHECK(bits_of(host::power(-2.0, -(edge + 1.0))) == bits_of(-1.0 / past_limit));
}

void squares_and_roots_match_ieee() {
    OA_CHECK(bits_of(host::power(0.0, 2.0)) == bits_of(0.0 * 0.0));
    OA_CHECK(bits_of(host::power(0.0, 0.5)) == bits_of(std::sqrt(0.0)));
    OA_CHECK(bits_of(host::power(-0.0, 0.5)) == bits_of(0.0));
    for (int index = 0; index < 400; ++index) {
        const int exponent = (index % 50) - 25;
        const double magnitude = std::ldexp(1.0 + (index % 19) * 0.05, exponent);
        const double positive = magnitude < 0.0 ? -magnitude : magnitude;
        OA_CHECK(bits_of(host::power(magnitude, 2.0)) == bits_of(magnitude * magnitude));
        OA_CHECK(bits_of(host::power(positive, 0.5)) == bits_of(std::sqrt(positive)));
    }
}

void expect_bits(const char* label, double got, uint64_t expected) {
    if (bits_of(got) != expected)
        std::fprintf(stderr, "special %s\n", label);
    OA_CHECK(bits_of(got) == expected);
}

void expect_nan(const char* label, double got) {
    if (!nan_bits(got))
        std::fprintf(stderr, "special nan %s\n", label);
    OA_CHECK(nan_bits(got));
}

